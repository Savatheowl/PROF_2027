"""Генерация тестовых учебных материалов для smoke-теста загрузчика."""
import pymupdf

TEXT = """Обыкновенные дроби

Дробь — это число, которое показывает часть целого. Дробь состоит из числителя и знаменателя. Числитель показывает, сколько частей взяли, а знаменатель — на сколько равных частей разделили целое.

Примеры. Дробь 1/2 читается «одна вторая». Если торт разделить на четыре равные части и взять три, получится дробь 3/4.

Сложение дробей. Чтобы сложить дроби с одинаковыми знаменателями, нужно сложить числители, а знаменатель оставить прежним. Например, 1/5 + 2/5 = 3/5. Для дробей с разными знаменателями сначала приводят их к общему знаменателю.

Сравнение дробей. Из двух дробей с одинаковыми знаменателями больше та, у которой больше числитель. Дробь с числителем меньше знаменателя называется правильной, она всегда меньше единицы.

Задачи для закрепления. Сложите дроби 2/7 и 3/7. Сравните дроби 5/9 и 7/9. Найдите, какая часть часа составляет 15 минут.

Домашнее задание. Решите десять примеров из учебника на стр. 45. Запишите решения в тетрадь и проверьте себя.
"""


def main() -> None:
    doc = pymupdf.open()
    page = doc.new_page()
    page.insert_text((72, 72), TEXT, fontsize=11,
                     fontname="times", fontfile=r"C:\Windows\Fonts\times.ttf")
    doc.save("data/incoming/fractions.pdf")
    doc.close()
    print("saved data/incoming/fractions.pdf")


if __name__ == "__main__":
    main()
