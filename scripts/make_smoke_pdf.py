def main() -> None:
    out = Path("data/incoming")
    out.mkdir(parents=True, exist_ok=True)
    for m in MATERIALS:
        doc = pymupdf.open()
        page = doc.new_page()
        page.insert_text((72, 72), m["text"], fontsize=11,
                         fontname="times", fontfile=FONT)
        fp = out / f"{m['name']}.pdf"
        doc.save(str(fp))
        doc.close()
        print(f"saved {fp}")
    print("done")


if __name__ == "__main__":
    main()
